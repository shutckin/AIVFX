/**
 * Партнёрские ссылки. Единственное место, где они лежат.
 *
 * Зачем отдельный файл: ссылка с партнёрской меткой рано или поздно
 * меняется, и менять её в двадцати статьях руками - гарантированная
 * потеря денег на забытом абзаце. В статьях пишем `partner:syntx`
 * вместо адреса, а реальный адрес подставляется отсюда.
 *
 * Правила по таким ссылкам:
 * - в разметке они уходят с rel="sponsored nofollow", чтобы поисковик
 *   видел, что это реклама, а не рекомендация редакции;
 * - партнёрский блок ставим только там, где человек и так ищет способ
 *   оплаты. В обзорных статьях его не место: обзор превращается в
 *   рекламу, и Яндекс за это понижает страницу.
 */

import { reachGoal } from '../lib/metrika';

export const PARTNERS = {
  syntx: {
    name: 'SYNTX',
    url: 'https://t.me/syntxaibot?start=aff_572494981',
    ru: {
      /* строка в тексте: row + имя + rowTail; short + имя в боковой колонке */
      row: 'Мы платим за модели рублями через ',
      rowTail: ': подписка одна, карта российская',
      short: 'Оплата рублями: ',
      action: 'Открыть',
    },
    /* Для англоязычного читателя рубли и карта «Мир» не значат ничего.
       Ему продаёт другой аргумент: одна подписка вместо пяти отдельных,
       и оплата, которая проходит, если своя карта не принимается. */
    en: {
      row: 'We run the models through ',
      rowTail: ': one subscription instead of five separate ones',
      short: 'One subscription: ',
      action: 'Open',
    },
  },
};

/**
 * Метка страницы для журнала кликов: 'runway-v-rossii', 'en.claude-v-2026'.
 * Считается в браузере; при пререндере Puppeteer открывает ту же страницу,
 * поэтому адрес в готовом HTML и после загрузки совпадает.
 */
const pageTag = () => {
  if (typeof window === 'undefined') return '';
  const path = window.location.pathname.replace(/^\/+|\/+$/g, '');
  return path.replace(/^en\/blog\//, 'en.').replace(/^blog\//, '').replace(/\//g, '.') || 'home';
};

/**
 * Адрес партнёрской ссылки на сайте. Ведёт не сразу к партнёру, а через
 * наш сервер: /go/<id>?from=<страница>.<место>. Сервер (nginx, location
 * /go/syntx) записывает клик в /var/log/aivfx-partner/clicks.log и
 * перекидывает на партнёрскую ссылку. Так клик виден, даже если
 * Метрику режет блокировщик.
 *
 * ВАЖНО: адрес назначения зашит и в конфиге nginx. Сменилась ссылка в
 * PARTNERS - поменять её и там, иначе переход уйдёт на старую.
 * place: facts, row, side, text. Неизвестный id - пустая строка.
 */
export const partnerUrl = (id, place = 'link') =>
  PARTNERS[id] ? `/go/${id}?from=${encodeURIComponent(`${pageTag()}.${place}`)}` : '';

/** Тексты партнёрского блока под язык страницы. */
export const partnerText = (id, locale) => {
  const p = PARTNERS[id];
  if (!p) return null;
  return { name: p.name, url: p.url, ...(locale === 'en' ? p.en : p.ru) };
};

/**
 * Отметить клик по партнёрской ссылке как цель в Метрике (partner_<id>).
 *
 * Нужно, чтобы понимать, доходит ли поисковый трафик до кнопки: в кабинете
 * партнёрки видно только оплаты, а не переходы. Второй, независимый от
 * блокировщиков учёт - журнал сервера на /go/<id>, см. partnerUrl.
 */
export const trackPartnerClick = (id) => reachGoal(`partner_${id}`);
