// Проверка свежести версий моделей в статьях.
// Запуск: node scripts/check-versions.js   (или npm run check:versions)
//
// Зачем: 04.09.2026 мы обновили в старых гайдах версии моделей (Veo 3.1,
// Runway Gen-4.5) - и показы в Google выросли с 6 до 41 в день. То есть
// свежесть версий это рычаг, а не косметика. Руками это каждый месяц
// перечитывать нереально: 37 статей и столько же английских версий.
//
// Скрипт НЕ знает, что вышло нового: он знает только таблицу ниже. Поэтому
// работа начинается с того, что человек сверяет таблицу по ссылкам, ставит
// новую дату в CHECKED_AT, и только потом запускает проверку.

const fs = require('fs');
const path = require('path');

// ── Таблица версий ──────────────────────────────────────────────────
// Сверять по официальным страницам, а не по статьям в интернете.
const CHECKED_AT = '2026-09-04';   // когда таблицу последний раз сверяли руками
const TABLE_TTL_DAYS = 45;         // дольше этого таблице верить нельзя

const MODELS = [
  {
    имя: 'Google Veo',
    версия: '3.1',
    сверять: 'https://deepmind.google/models/veo/',
    // Veo 3.1, Veo 2 и т.п.
    регексп: /Veo\s+(\d+(?:\.\d+)?)/g,
  },
  {
    имя: 'Runway Gen',
    версия: '4.5',
    сверять: 'https://runwayml.com/research',
    // Gen-4.5, Gen-4; «Gen-4 Turbo» это отдельная живая модель, не старая версия
    регексп: /Gen-(\d+(?:\.\d+)?)(?!\s+Turbo)/g,
  },
  {
    имя: 'Kling',
    версия: '3.0',
    сверять: 'https://app.klingai.com/',
    регексп: /Kling\s+(\d+(?:\.\d+)?)/g,
  },
  {
    имя: 'Seedance',
    версия: '2.5',
    сверять: 'https://seed.bytedance.com/',
    регексп: /Seedance\s+(\d+(?:\.\d+)?)/g,
  },
  {
    имя: 'MiniMax Hailuo',
    версия: '3.0',
    сверять: 'https://hailuoai.video/',
    регексп: /Hailuo\s+(\d+(?:\.\d+)?)/g,
  },
];

// Слова, которыми текст объявляет версию самой новой. Только рядом с ними
// старая версия это ошибка: «пришла на смену Hailuo 2.3» или «Gen-4 Turbo
// для черновиков» - нормальные исторические упоминания, их не трогаем.
const ЗАЯВКА_НА_НОВИЗНУ = /(последн|новейш|актуальн|сама[яй] нов|свежая версия|на сегодня|на данный момент|сейчас лучш|latest|newest|current version|as of)/i;

// Сколько дней статья может не пересматриваться, прежде чем попасть в список
const СТАТЬЯ_TTL_DAYS = 60;

const DATA = path.join(__dirname, '..', 'src', 'data');
const ФАЙЛЫ = fs.readdirSync(DATA)
  .filter((f) => f.endsWith('.js'))
  .map((f) => path.join(DATA, f));

const дней = (iso) => Math.floor((Date.now() - new Date(iso).getTime()) / 86400000);
const версияЧисло = (v) => {
  const [a, b] = String(v).split('.');
  return Number(a) * 1000 + Number(b || 0);
};

const ошибки = [];
const предупреждения = [];
const кПересмотру = [];

// ── Таблица не должна протухать сама ────────────────────────────────
if (дней(CHECKED_AT) > TABLE_TTL_DAYS) {
  ошибки.push(`таблица версий сверялась ${дней(CHECKED_AT)} дней назад (${CHECKED_AT}).\n`
    + '      Сначала сверьте её по ссылкам «сверять» в scripts/check-versions.js\n'
    + '      и поставьте новую дату в CHECKED_AT, иначе проверка врёт.');
}

// ── Разбор статей ───────────────────────────────────────────────────
// Файлы данных это модули, но нам нужны номера строк и границы статей,
// поэтому читаем их как текст, а статьи режем по строке «slug:».
const статьи = [];
for (const файл of ФАЙЛЫ) {
  const текст = fs.readFileSync(файл, 'utf8');
  const метки = [...текст.matchAll(/\n\s*slug: '([^']+)'/g)];
  if (!метки.length) continue;
  метки.forEach((м, i) => {
    const начало = м.index;
    const конец = i + 1 < метки.length ? метки[i + 1].index : текст.length;
    const тело = текст.slice(начало, конец);
    const dm = тело.match(/dateModified: '([^']+)'/);
    статьи.push({
      файл: path.relative(path.join(__dirname, '..'), файл),
      slug: м[1],
      обновлена: dm ? dm[1] : null,
      строка: текст.slice(0, начало).split('\n').length,
      тело,
    });
  });
}

for (const статья of статьи) {
  const моделиВСтатье = new Set();

  // предложения нужны, чтобы заявка на новизну и версия стояли рядом
  const предложения = статья.тело.split(/(?<=[.!?])\s+/);
  for (const предложение of предложения) {
    for (const модель of MODELS) {
      const найденные = [...предложение.matchAll(модель.регексп)].map((m) => m[1]);
      if (!найденные.length) continue;
      моделиВСтатье.add(модель.имя);

      for (const v of найденные) {
        if (версияЧисло(v) > версияЧисло(модель.версия)) {
          предупреждения.push(`${статья.slug}: в тексте ${модель.имя} ${v}, в таблице ${модель.версия}.`
            + ' Похоже, вышла новая версия и таблицу пора обновить.');
          continue;
        }
        // Если в том же предложении названа и текущая версия, это перечисление
        // линейки («актуальные модели - Gen-4, Gen-4 Turbo и Gen-4.5»), а не
        // устаревшая подача. Нашлось на runway-v-rossii при первом прогоне.
        const естьТекущая = найденные.some((x) => версияЧисло(x) === версияЧисло(модель.версия));
        if (версияЧисло(v) < версияЧисло(модель.версия) && ЗАЯВКА_НА_НОВИЗНУ.test(предложение) && !естьТекущая) {
          ошибки.push(`${статья.slug} (${статья.файл}): ${модель.имя} ${v} подана как актуальная,`
            + ` а сейчас ${модель.версия}.\n      «${предложение.replace(/\s+/g, ' ').trim().slice(0, 160)}»`);
        }
      }
    }
  }

  if (моделиВСтатье.size && статья.обновлена && дней(статья.обновлена) > СТАТЬЯ_TTL_DAYS) {
    кПересмотру.push({
      slug: статья.slug,
      язык: /_en_/.test(статья.файл) ? 'EN' : 'RU',
      файл: статья.файл,
      дней: дней(статья.обновлена),
      модели: [...моделиВСтатье].join(', '),
    });
  }
}

// ── Отчёт ───────────────────────────────────────────────────────────
console.log(`\nСтатей просмотрено: ${статьи.length}. Таблица версий сверялась ${дней(CHECKED_AT)} дней назад.`);

if (ошибки.length) {
  console.log(`\nПРОТУХШИЕ ВЕРСИИ (${ошибки.length}):`);
  ошибки.forEach((e) => console.log('  - ' + e));
}

if (предупреждения.length) {
  console.log(`\nТАБЛИЦА ОТСТАЁТ (${предупреждения.length}):`);
  предупреждения.forEach((e) => console.log('  - ' + e));
}

if (кПересмотру.length) {
  console.log(`\nПОРА СВЕРИТЬ ФАКТЫ, статей ${кПересмотру.length} (самые залежавшиеся сверху):`);
  кПересмотру.sort((a, b) => b.дней - a.дней)
    .forEach((s) => console.log(`  ${String(s.дней).padStart(3)} дн  ${s.язык}  ${s.slug.padEnd(34)} ${s.модели}`));
}

if (!ошибки.length && !предупреждения.length && !кПересмотру.length) {
  console.log('\nВсё свежее: протухших версий нет, статьи пересмотрены недавно.\n');
}

console.log('');
process.exit(ошибки.length ? 1 : 0);
